namespace Tempo.Blazor.Components.Inputs;

/// <summary>The height of a <see cref="TmSegmentedControl{TValue}"/> tray.</summary>
public enum SegmentedControlSize
{
    /// <summary>Compact (32 px, the small input height).</summary>
    Sm,

    /// <summary>Default (38 px, the medium input height).</summary>
    Md,

    /// <summary>Roomy (44 px, the large input height — the same block size a finger needs).</summary>
    Lg
}
